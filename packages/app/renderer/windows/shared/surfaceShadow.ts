/**
 * 透明无边框窗内「可见表面」的统一投影档
 *
 * 这类窗口（`transparent: true` + `frame: false` + `hasShadow: false`）的投影全靠 CSS 画，
 * 而 CSS 投影**只能画在窗口边界内**：超出窗口的部分被直接裁掉，不会像原生投影那样溢到窗外
 * 可用的扩散距离因此被四周那圈透明留白（`SHADOW_INSET`）定死，档位不能随便挑
 *
 * 换算依据：CSS 规范把 `box-shadow` 的 blur 定义为标准差 σ = blur / 2 的高斯模糊，
 * 距投影边 d 处的残余不透明度约为 `A · Q(d / σ)`（Q 为标准正态的尾概率）
 * 要低于 1/255 需要 d ≈ 2.2σ，也就是说 blur 越大，需要的留白越大：
 *
 * - 本档最外层 `0 8px 24px / 0.12`：σ = 12，需要约 27px。留白 30px 时，
 *   下沿实际只剩 30 − 8（offset）= 22px 可用，残余约 1/255；左右满 30px，残余约 0
 * - 全局 `shadow-card`（`0 8px 48px / 0.15`）：σ = 24，需要约 53px。同样 30px 留白下
 *   会被拦腰截断，下沿残余 7/255、左右 4/255——渲染出来就是绕着面板的一圈笔直灰边，
 *   也就是肉眼看到的「阴影不自然」。所以窗口边界内的表面一律不用它
 *
 * 主窗内部的元素不受窗口边界约束，继续用 `shadow-card`，不必跟这一档
 *
 * 另注：只有当可见轮廓与元素自身的 border-box 一致（有背景色的圆角矩形 / 药丸）时才用
 * `box-shadow`；投影要跟随子元素画出的异形轮廓时，得改用 `drop-shadow` 滤镜
 */
